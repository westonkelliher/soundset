// bake.js — selected cues -> <out>/<cue>.<n>.ogg (n = seed; 0 is exactly what was reviewed) + manifest.json
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { execFileSync } from "node:child_process";
import { withHeadless } from "./headless.js";
import { fileURLToPath } from "node:url";
import { readJson, writeJson } from "./project.js";

const PLAYER = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "player", "soundset-player.js");

export async function bake(proj, a) {
  const out = path.resolve(proj.dir, proj.config.out || "out");
  fs.mkdirSync(out, { recursive: true });
  const cues = (a._.length ? a._ : proj.cueNames).filter((c) => proj.status(c) === "selected");
  if (!cues.length) return console.log("nothing selected yet — nothing to bake");
  const manifestPath = path.join(out, "manifest.json");
  const manifest = readJson(manifestPath, { cues: {} });
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "soundset-"));
  const q = String(proj.config.oggQuality ?? 6);
  await withHeadless(proj.dir, async (hl) => {
    for (const cue of cues) {
      const sel = proj.cueState(cue).selected;
      const rel = proj.patchRel(cue, sel.round, sel.id);
      const patch = proj.patch(cue, sel.round, sel.id);
      // seeds change rand/pick values and noise/pluck/modal/unison randomness; a fully deterministic patch gets 1 file
      // (variation then comes from playback jitter only)
      const s = JSON.stringify(patch);
      const varies = /"(rand|pick)"|"type":\s*"(noise|pluck|modal)"|"unison"|"reverb"/.test(s);
      const n = varies ? (proj.cue(cue).variants ?? proj.config.variants ?? 4) : 1;
      for (const f of fs.readdirSync(out)) if (f.startsWith(cue + ".") && f.endsWith(".ogg")) fs.rmSync(path.join(out, f));
      const files = [];
      for (let seed = 0; seed < n; seed++) {
        const r = await hl.render(rel, { ...proj.renderOpts(cue), seed });
        const wav = path.join(tmp, `${cue}.${seed}.wav`), ogg = `${cue}.${seed}.ogg`;
        fs.writeFileSync(wav, Buffer.from(r.wav, "base64"));
        execFileSync("ffmpeg", ["-v", "error", "-y", "-i", wav, "-c:a", "libvorbis", "-q:a", q, path.join(out, ogg)]);
        files.push(ogg);
        if (seed === 0) console.log(`${cue.padEnd(18)} r${sel.round}${sel.id} ×${n}  ${r.metrics.durMs}ms  ${r.metrics.lufsM} LUFS-M`);
      }
      manifest.cues[cue] = { files, patch: rel, loudness: proj.loudness(cue), play: proj.playOpts(cue) };
    }
  });
  fs.rmSync(tmp, { recursive: true, force: true });
  manifest.generated = new Date().toISOString();
  manifest.note = "generated by `soundset bake`; play: pitch = ±cents jitter, gain = ±dB jitter, voices = max simultaneous, cooldown = min ms between triggers";
  writeJson(manifestPath, manifest);
  fs.copyFileSync(PLAYER, path.join(out, "soundset-player.js"));
  console.log(`\n${cues.length} cue(s) -> ${out}`);
}
